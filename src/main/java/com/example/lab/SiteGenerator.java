package com.example.lab;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

/**
 * 静态站点生成器。
 *
 * <p>原 Python 实验用 MkDocs（第三方工具）来生成文档站点；
 * 本 Java 进阶实验改为"自己用 Java 写生成器"，把实验说明与计算器
 * 的运行结果生成为一组 HTML 文件，再由部署工作流发布到 GitHub Pages。
 * 这样既锻炼了 Java 文件 IO 与字符串拼接能力，也让部署内容完全可控。</p>
 *
 * <p>用法： {@code java com.example.lab.SiteGenerator <输出目录>}</p>
 */
public class SiteGenerator {

    public static void main(String[] args) throws IOException {
        String outputDir = args.length > 0 ? args[0] : "target/site";
        Path out = Paths.get(outputDir);
        Files.createDirectories(out);

        Calculator calc = new Calculator();

        write(out, "index.html", page("首页",
            "欢迎使用 Java 自动化实验站点",
            "本站点由 <strong>SiteGenerator</strong>（纯 Java 程序）在 GitHub Actions 中生成，"
                + "并自动部署到 GitHub Pages。它替代了原 Python 实验中的 MkDocs。",
            nav()));

        write(out, "about.html", page("关于",
            "关于本项目",
            "本项目使用 Maven 构建，配套 JUnit 5 单元测试与 JaCoCo 覆盖率，"
                + "并通过 GitHub Actions 实现持续集成（CI）与持续部署（CD）。",
            nav()));

        write(out, "guide.html", page("使用指南",
            "使用指南",
            "1. 编写 Java 代码与 JUnit 5 单元测试<br>"
                + "2. 提交代码到 GitHub<br>"
                + "3. GitHub Actions 自动编译、测试并生成覆盖率报告<br>"
                + "4. 部署工作流自动生成静态站点并发布到 GitHub Pages",
            nav()));

        write(out, "api.html", page("API 参考",
            "API 参考（Calculator 方法示例）",
            apiTable(calc),
            nav()));

        write(out, "report.html", page("运行报告",
            "计算器运行报告（由 Java 实时计算生成）",
            reportTable(calc),
            nav()));

        Files.write(out.resolve("styles.css"), CSS.getBytes(StandardCharsets.UTF_8));

        System.out.println("站点已生成至: " + out.toAbsolutePath());
    }

    private static String nav() {
        return "<nav>"
            + "<a href='index.html'>首页</a> | "
            + "<a href='about.html'>关于</a> | "
            + "<a href='guide.html'>指南</a> | "
            + "<a href='api.html'>API</a> | "
            + "<a href='report.html'>报告</a>"
            + "</nav>";
    }

    private static String page(String title, String heading, String body, String nav) {
        return "<!DOCTYPE html><html lang='zh-CN'><head>"
            + "<meta charset='UTF-8'>"
            + "<meta name='viewport' content='width=device-width, initial-scale=1.0'>"
            + "<title>" + title + " - Java Actions Lab</title>"
            + "<link rel='stylesheet' href='styles.css'>"
            + "</head><body>"
            + nav
            + "<main><h1>" + heading + "</h1><p>" + body + "</p></main>"
            + "<footer><p>Generated by Java SiteGenerator &middot; GitHub Actions + Pages</p></footer>"
            + "</body></html>";
    }

    private static String apiTable(Calculator c) {
        StringBuilder sb = new StringBuilder("<table><tr><th>方法</th><th>示例</th><th>结果</th></tr>");
        sb.append(row("add(2, 3)", String.valueOf(c.add(2, 3))));
        sb.append(row("subtract(10, 4)", String.valueOf(c.subtract(10, 4))));
        sb.append(row("multiply(6, 7)", String.valueOf(c.multiply(6, 7))));
        sb.append(row("divide(9, 3)", String.valueOf(c.divide(9, 3))));
        sb.append(row("factorial(5)", String.valueOf(c.factorial(5))));
        sb.append("</table>");
        return sb.toString();
    }

    private static String reportTable(Calculator c) {
        StringBuilder sb = new StringBuilder("<table><tr><th>表达式</th><th>结果</th></tr>");
        for (int i = 1; i <= 10; i++) {
            sb.append(row("factorial(" + i + ")", String.valueOf(c.factorial(i))));
        }
        sb.append("</table>");
        return sb.toString();
    }

    private static String row(String expr, String result) {
        return "<tr><td>" + expr + "</td><td>" + result + "</td></tr>";
    }

    private static final String CSS =
        "body{font-family:-apple-system,Segoe UI,Roboto,sans-serif;max-width:760px;"
            + "margin:40px auto;padding:0 16px;color:#222;line-height:1.6}"
            + "nav{background:#24292e;padding:12px 16px;border-radius:6px;margin-bottom:24px}"
            + "nav a{color:#fff;text-decoration:none;margin-right:12px}"
            + "h1{color:#0969da}table{border-collapse:collapse;width:100%;margin-top:16px}"
            + "th,td{border:1px solid #ddd;padding:8px 10px;text-align:left}"
            + "th{background:#f6f8fa}footer{margin-top:32px;color:#888;font-size:13px}";

    private static void write(Path dir, String name, String content) throws IOException {
        try (PrintWriter pw = new PrintWriter(Files.newBufferedWriter(dir.resolve(name)))) {
            pw.print(content);
        }
    }
}
